#!/usr/bin/env python3
OPNAMES = {0:'NOP',1:'ADD',2:'ADDI',3:'SUB',4:'AND',5:'OR',6:'XOR',7:'SLL',
           8:'SRL',9:'LW',0xA:'SW',0xB:'BEQ',0xC:'BLT',0xD:'JAL',0xE:'JALR',0xF:'HALT'}
RTYPE = {1,3,4,5,6}

def sext6(v):
    return v - 64 if (v & 0x20) else v

words = [
    0x2205, 0x240a, 0x1650, 0x3888, 0x4a50, 0x5a50, 0x6a50, 0x7c42,
    0x8d82, 0x223d, 0x3208, 0x240a, 0xa410, 0x9e10, 0x221f, 0x225f,
    0x225f, 0x2247, 0x241b, 0xa440, 0x9640, 0x2205, 0xb242, 0xf000,
    0x281f, 0x290b, 0x2900, 0x2900, 0x2a03, 0x2c01, 0x2400, 0x3b70,
    0x2481, 0xb142, 0xb03d, 0x2203, 0xc205, 0x261f, 0x26df, 0x26df,
    0x26d2, 0x261f, 0x26df, 0x26cf, 0x26c0, 0xd005, 0x281f, 0x291f,
    0x291f, 0x2912, 0x281f, 0x291f, 0x291a, 0x2900, 0x2200, 0x2240,
    0x2240, 0x2242, 0xe476, 0xf000, 0x2a1f, 0x2b5f, 0x2b44, 0x2b40,
    0x2430, 0x2480, 0x2480, 0x2480, 0x2220, 0x2260, 0x226a, 0x2240,
    0xa280, 0x9680, 0x9881, 0x243c, 0x2480, 0x2480, 0x2480, 0x221f,
    0x225f, 0x2242, 0x2240, 0xa280, 0x9c80, 0x2201, 0x2240, 0x2240,
    0x2240, 0xa2be, 0x9ebe, 0xf000,
]

for i, w in enumerate(words):
    addr = i * 2
    op = (w >> 12) & 0xF
    rd = (w >> 9) & 0x7
    rs1 = (w >> 6) & 0x7
    rs2 = (w >> 3) & 0x7
    imm6 = w & 0x3F
    name = OPNAMES[op]
    if op in RTYPE:
        txt = f"{name} r{rd}, r{rs1}, r{rs2}"
    elif op == 0xD:  # JAL
        txt = f"JAL  off={sext6(imm6)} (target=0x{(addr+sext6(imm6)*2)&0xFFFF:04x})"
    elif op in (0xB, 0xC):  # BEQ/BLT
        txt = f"{name} r{rs1}, r{rd}(2nd), off={sext6(imm6)} (target=0x{(addr+sext6(imm6)*2)&0xFFFF:04x})"
    elif op == 0xE:  # JALR
        txt = f"JALR rd=r{rd}, rs1=r{rs1}, imm={sext6(imm6)}"
    elif op in (7, 8):  # SLL/SRL
        txt = f"{name} r{rd}, r{rs1}, {imm6 & 7}"
    else:
        txt = f"{name} r{rd}, r{rs1}, {sext6(imm6)}"
    marker = "  <== JALR" if op == 0xE else ""
    print(f"0x{addr:04x} (idx{i:2d}): {w:04x}  {txt}{marker}")
